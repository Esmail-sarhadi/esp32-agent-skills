#!/usr/bin/env python3
"""Render data/esp32-pins.json into a human-readable reference table.

The JSON is the source of truth; this file exists so the same facts can be read
by a person without opening the JSON. Generating it means the table cannot drift
away from the data, and tests/test_reference.py fails if someone edits one and
forgets the other.

Usage:
    python tools/render_pin_table.py            # print to stdout
    python tools/render_pin_table.py --write    # rewrite the reference file
"""

from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(ROOT, "data", "esp32-pins.json")
OUT = os.path.join(ROOT, "skills", "esp32-pin-safety", "reference", "pin-table.md")

HEADER = """# ESP32 pin reference

Generated from `data/esp32-pins.json` by `tools/render_pin_table.py`.
Do not edit this file by hand: change the JSON and run the generator.

An empty cell means the pin has no constraint in that category. `note` carries
the strapping reason, because "strapping" alone does not tell you what to do.

"""


def render(soc_key: str, soc: dict) -> str:
    low, high = soc["valid_range"]
    flash = set(soc.get("reserved_flash", []))
    input_only = set(soc.get("input_only", []))
    uart0 = set(soc.get("uart0", []))
    adc2 = set(soc.get("adc2_blocked_by_wifi", []))
    usb = set(soc.get("usb", []))
    absent = set(soc.get("not_on_wroom", []))
    strapping = soc.get("strapping", {})

    lines = ["## %s" % soc["label"], "",
             "| GPIO | flash | input only | strapping | UART0 | ADC2 | USB | note |",
             "|---|---|---|---|---|---|---|---|"]

    for pin in range(low, high + 1):
        note = strapping.get(str(pin), "")
        if pin in absent:
            note = "not present on WROOM modules"
        lines.append("| %d | %s | %s | %s | %s | %s | %s | %s |" % (
            pin,
            "yes" if pin in flash else "",
            "yes" if pin in input_only else "",
            "yes" if str(pin) in strapping else "",
            "yes" if pin in uart0 else "",
            "yes" if pin in adc2 else "",
            "yes" if pin in usb else "",
            note,
        ))

    lines.append("")
    return "\n".join(lines)


def build() -> str:
    with open(DB, "r", encoding="utf-8") as handle:
        db = json.load(handle)
    parts = [HEADER]
    for key in ("esp32", "esp32s3", "esp32c3"):
        parts.append(render(key, db["socs"][key]))
    return "\n".join(parts)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Render the pin reference table.")
    parser.add_argument("--write", action="store_true", help="write the file instead of printing")
    args = parser.parse_args(argv)

    text = build()
    if args.write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), len(text.splitlines())))
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
