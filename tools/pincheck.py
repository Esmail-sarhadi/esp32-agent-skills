#!/usr/bin/env python3
"""Check an ESP32 pin assignment against the hardware constraints of the SoC.

Firmware generated by a coding agent usually compiles and then fails on real
hardware for reasons that are visible in the pin map alone: a GPIO wired to the
SPI flash, an input-only pin driven as an output, a strapping pin pulled the
wrong way at boot. This script catches those cases before the board is flashed.

Usage:
    python tools/pincheck.py --soc esp32 --assign "12=relay,34=button,6=led"
    python tools/pincheck.py --soc esp32s3 --file examples/pinmap.txt

Exit code is 1 when at least one error is found, 0 otherwise.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from typing import Dict, List, Tuple

ERROR = "error"
WARN = "warn"
INFO = "info"
OK = "ok"

DB_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "esp32-pins.json")

PIN_RE = re.compile(r"^(?:gpio)?(\d{1,2})$", re.IGNORECASE)


def load_db(path: str = DB_PATH) -> dict:
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def parse_assignment(raw: str) -> List[Tuple[int, str]]:
    """Turn ``12=relay,34=button`` into ``[(12, 'relay'), (34, 'button')]``."""
    result: List[Tuple[int, str]] = []
    for chunk in re.split(r"[,\n;]+", raw):
        chunk = chunk.strip()
        if not chunk:
            continue
        if "=" in chunk:
            pin_part, label = chunk.split("=", 1)
        else:
            pin_part, label = chunk, "unnamed"
        match = PIN_RE.match(pin_part.strip())
        if not match:
            raise ValueError("cannot read pin %r, expected GPIO<n> or <n>" % pin_part)
        result.append((int(match.group(1)), label.strip() or "unnamed"))
    return result


def check_pin(soc: dict, pin: int, label: str, seen: Dict[int, str]) -> List[Tuple[str, str]]:
    """Return a list of ``(severity, message)`` findings for a single pin."""
    findings: List[Tuple[str, str]] = []
    low, high = soc["valid_range"]

    if pin < low or pin > high:
        findings.append((ERROR, "GPIO%d does not exist on %s (valid range %d-%d)"
                         % (pin, soc["label"], low, high)))
        return findings

    if pin in seen:
        findings.append((ERROR, "GPIO%d is assigned twice (%r and %r), a pin can only do one job"
                         % (pin, seen[pin], label)))

    if pin in soc["reserved_flash"]:
        findings.append((ERROR, "GPIO%d is connected to the SPI flash, using it bricks the module"
                         % pin))

    if pin in soc["not_on_wroom"]:
        findings.append((ERROR, "GPIO%d is not available on WROOM modules (%s)"
                         % (pin, soc["notes"].get("not_on_wroom", ""))))

    if pin in soc["input_only"]:
        findings.append((WARN, "GPIO%d is input-only: it cannot drive an output and has no "
                               "internal pull-up or pull-down, add an external resistor for %r"
                         % (pin, label)))

    if str(pin) in soc["strapping"]:
        findings.append((WARN, "GPIO%d is a strapping pin and %s; make sure %r cannot hold it "
                               "there at reset"
                         % (pin, soc["strapping"][str(pin)], label)))

    if pin in soc.get("usb", []):
        findings.append((INFO, "GPIO%d is a native USB pin, driving it as GPIO disables the USB "
                               "serial console on %s" % (pin, soc["label"])))

    if pin in soc["uart0"]:
        findings.append((INFO, "GPIO%d is UART0 by default, the serial monitor owns it until you "
                               "remap the console" % pin))

    if pin in soc["adc2_blocked_by_wifi"]:
        findings.append((INFO, "GPIO%d is on ADC2, analogRead() returns garbage while Wi-Fi is "
                               "active" % pin))

    if not findings:
        findings.append((OK, "no constraint found in the database"))
    return findings


def run(soc_key: str, assignments: List[Tuple[int, str]], db: dict) -> Tuple[List[dict], int]:
    soc = db["socs"][soc_key]
    seen: Dict[int, str] = {}
    report: List[dict] = []
    errors = 0

    for pin, label in assignments:
        findings = check_pin(soc, pin, label, seen)
        seen.setdefault(pin, label)
        for severity, message in findings:
            if severity == ERROR:
                errors += 1
        report.append({"pin": pin, "label": label, "findings": findings})
    return report, errors


def print_report(report: List[dict], soc_label: str) -> None:
    order = {ERROR: 0, WARN: 1, INFO: 2, OK: 3}
    flat = []
    for entry in report:
        for severity, message in entry["findings"]:
            flat.append((order[severity], entry["pin"], entry["label"], severity, message))
    flat.sort()

    print("%s - %d pin(s) checked\n" % (soc_label, len(report)))
    for _, pin, label, severity, message in flat:
        print("  GPIO%-2d  %-5s  %-14s %s" % (pin, severity.upper(), label, message))

    counts = {}
    for entry in report:
        for severity, _ in entry["findings"]:
            counts[severity] = counts.get(severity, 0) + 1
    print("\n  %d error(s), %d warning(s), %d note(s)"
          % (counts.get(ERROR, 0), counts.get(WARN, 0), counts.get(INFO, 0)))


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Validate an ESP32 pin assignment.")
    parser.add_argument("--soc", default="esp32", help="esp32, esp32s3 or esp32c3")
    parser.add_argument("--assign", help='inline list, e.g. "12=relay,34=button"')
    parser.add_argument("--file", help="file with one assignment per line, # starts a comment")
    parser.add_argument("--json", action="store_true", help="machine readable output")
    args = parser.parse_args(argv)

    db = load_db()
    if args.soc not in db["socs"]:
        parser.error("unknown SoC %r, pick one of: %s" % (args.soc, ", ".join(db["socs"])))

    raw = args.assign or ""
    if args.file:
        with open(args.file, "r", encoding="utf-8") as handle:
            raw += "\n" + "\n".join(line.split("#", 1)[0] for line in handle)
    if not raw.strip():
        parser.error("nothing to check, pass --assign or --file")

    try:
        assignments = parse_assignment(raw)
    except ValueError as exc:
        parser.error(str(exc))

    report, errors = run(args.soc, assignments, db)
    if args.json:
        print(json.dumps({"soc": args.soc, "errors": errors, "pins": report}, indent=2))
    else:
        print_report(report, db["socs"][args.soc]["label"])
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
