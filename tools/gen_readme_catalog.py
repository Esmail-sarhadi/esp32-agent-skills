#!/usr/bin/env python3
"""Generate the README skills catalog from the skills directory.

The catalog is a generated artifact, not a hand-written list. Every row comes
from a SKILL.md frontmatter description, so the table cannot claim a skill that
does not exist or forget one that does. The corpus test
``test_readme_lists_every_skill`` enforces the second half; ``--check`` here
enforces both halves in CI before the test suite even runs.

    python tools/gen_readme_catalog.py
    python tools/gen_readme_catalog.py --check

To add a skill: add the directory, then run this script. Do not edit the table
between the markers by hand - the next run will overwrite it.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILLS = os.path.join(ROOT, "skills")
README = os.path.join(ROOT, "README.md")

START = "<!-- SKILLS CATALOG START -->"
END = "<!-- SKILLS CATALOG END -->"
HEADER = "| Skill | Covers |\n|---|---|"


def parse_description(text: str) -> str:
    """Read the frontmatter description and turn it into a table cell."""
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise ValueError("no frontmatter")
    for line in match.group(1).splitlines():
        if line.strip().startswith("description:"):
            desc = line.split("description:", 1)[1].strip()
            if desc.lower().startswith("use when "):
                desc = desc[len("use when "):]
            # A pipe would break the Markdown table.
            desc = desc.replace("|", "\\|")
            return desc[0].upper() + desc[1:] if desc else ""
    raise ValueError("no description in frontmatter")


def build_catalog() -> str:
    """The full generated block, markers included."""
    rows = []
    for name in sorted(os.listdir(SKILLS)):
        path = os.path.join(SKILLS, name, "SKILL.md")
        if not os.path.isfile(path):
            continue
        with open(path, "r", encoding="utf-8") as handle:
            desc = parse_description(handle.read())
        rows.append("| `%s` | %s |" % (name, desc))
    return "\n".join([
        START,
        "",
        "Generated by `tools/gen_readme_catalog.py` from each `SKILL.md` "
        "frontmatter. Do not edit the table by hand.",
        "",
        HEADER,
        *rows,
        "",
        END,
    ])


def read_readme() -> str:
    with open(README, "r", encoding="utf-8") as handle:
        return handle.read()


def splice(text: str, block: str) -> str:
    """Replace the marked region, or append a new section if none exists."""
    if START in text and END in text:
        before, rest = text.split(START, 1)
        _, after = rest.split(END, 1)
        return before + block + after

    marker = "\n## Repository structure\n"
    if marker not in text:
        raise ValueError("no catalog markers and no '## Repository structure' to insert before")
    section = "\n## Skills catalog\n\n" + block + "\n"
    return text.replace(marker, section + marker, 1)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the README catalog differs from the tree")
    args = parser.parse_args(argv)

    block = build_catalog()
    current = read_readme()

    if START in current and END in current:
        expected = splice(current, block)
        matches = current == expected
    else:
        matches = False
        expected = splice(current, block)

    if args.check:
        if not matches:
            print("out of date: README.md (skills catalog)", file=sys.stderr)
            print("run: python tools/gen_readme_catalog.py", file=sys.stderr)
            return 1
        print("README skills catalog matches the tree")
        return 0

    if not matches:
        with open(README, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(expected)
        print("wrote README.md skills catalog (%d skills)" % block.count("\n| `"))
    else:
        print("README.md skills catalog already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
